import { BusinessLead } from '../types';

export interface PitchTemplate {
  id: string;
  title: string;
  channel: 'whatsapp' | 'call' | 'email' | 'instagram_dm';
  text: string;
}

export function generatePitchTemplates(lead: BusinessLead): PitchTemplate[] {
  const category = lead.category || 'бизнес';
  const name = lead.name || 'Компания';
  const city = lead.city || 'города';
  const rating = lead.rating || 4.8;
  const reviews = lead.reviews || 20;

  return [
    {
      id: 'whatsapp-direct',
      title: 'WhatsApp / Telegram: Прямое предложение (Конверсия 35%+)',
      channel: 'whatsapp',
      text: `Здравствуйте, ${name}! 👋

Меня зовут [Ваше имя], занимаюсь веб-разработкой и привлечением клиентов для компаний в сфере "${category}" в ${city}.

Обратил внимание на ваш высокий рейтинг (${rating}★, ${reviews} отзывов на картах) — видно, что клиенты вас ценят! Но заметил, что у вас пока нет полноценного сайта/лендинга с онлайн-записью.

Сейчас из-за этого вы можете терять 30-40% горячих клиентов, которые ищут "${category} ${city}" в Google/Яндекс.

Могу подготовить для вас бесплатный демо-макет сайта за 24 часа. Будет ли вам интересно взглянуть на концепт?`
    },
    {
      id: 'call-script',
      title: 'Скрипт холодного звонка администратору / владельцу',
      channel: 'call',
      text: `— Добрый день! Это ${name}?
— (Ответ)
— Подскажите, пожалуйста, с кем могу переговорить по поводу маркетинга и привлечения клиентов из интернета?
— (Перевод на руководителя)
— Здравствуйте! Меня зовут [Ваше имя]. Нашел вас на картах с отличным рейтингом ${rating}, но увидел, что у вас не прикреплен сайт. Мы делаем продающие сайты для сферы "${category}" в ${city}, которые окупаются за первый месяц. 
Хотел предложить бесплатно показать структуру сайта, которая приведет вам новых клиентов. В какой мессенджер удобнее скинуть пример?`
    },
    {
      id: 'instagram-dm',
      title: 'Сообщение в Instagram Direct / Соцсети',
      channel: 'instagram_dm',
      text: `Приветствуем команду ${name}! ✨
Отличный профиль и супер отзывы на картах (${rating}★)! 

Заметили, что в шапке профиля нет ссылки на удобный сайт-визитку или онлайн-каталог с записью. Мы специализируемся на разработке стильных мобильных сайтов для ${category}.

Хотим сделать для вас подарок — бесплатный аудит и прототип сайта для ${city}. Скинуть ссылку на пример в директ?`
    },
    {
      id: 'email-pitch',
      title: 'Деловое коммерческое предложение (Email)',
      channel: 'email',
      text: `Тема: Предложение по привлечению клиентов для ${name} (${city})

Уважаемый руководитель ${name},

Анализируя локальный рынок ${city} по направлению "${category}", мы выделили вашу компанию благодаря высокой лояльности клиентов (${rating} звезды, ${reviews} отзывов).

При этом поиск в Google и 2GIS показал отсутствие официального сайта, что снижает конверсию поискового трафика на 40-50%.

Что мы предлагаем разработать:
1. Быстрый адаптивный сайт с каталогом услуг и прайсом
2. Интеграцию с WhatsApp/Telegram для мгновенных заявок
3. Оптимизацию под локальное SEO в ${city}

Готовы созвониться на 10 минут в удобное для вас время или выслать кейсы реализованных проектов.`
    }
  ];
}
